#!/usr/bin/env python3
"""build/names.py -- turn data/names.json into the loadable Ess.Names table, and (re)import that json.

Ess.Names (src/07_names.lua) reverses a `0xHASH` back to the name it was hashed from, using a ~23k-entry
lookup table. That table is FAR too big to fold into the one merged Ess.lua every user loads, so it ships as
its own opt-in file:

    dist/EssNames.lua   ->  release zip  ->  scripts/OnLoad/2_EssNames.lua

which sets the global `__EssNamesDB`; the namespace adopts it lazily, so load order doesn't matter (see the
07_names.lua header). package.py calls this during a release build. It is the exact sibling of natives.json:
a data artifact CI cannot regenerate on its own (it comes from the retail-WAD-verified upstream), so the
source `data/names.json` is COMMITTED and this only transcribes it.

Two commands:

    python build/names.py                       data/names.json -> dist/EssNames.lua   (the build step)
    python build/names.py --import <names.json>  (re)write data/names.json from the upstream Mercs2 workshop
                                                 export (its production_names.json / names.bin), canonically.

The generated Lua is written in batches of a few thousand entries, each merged by a tiny local helper rather
than one giant `{...}` literal: a single Lua 5.1 function has a hard cap on constants, and a 23k-entry
constructor is close enough to it that splitting is the safe, boring choice. Keys are canonicalised to the
`"0xAABBCCDD"` form (0x + upper-case, 8 wide) that Sys.GuidToString emits and 07_names.lua's norm() expects.
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "names.json"
DIST = ROOT / "dist"
OUT = DIST / "EssNames.lua"

BATCH = 4000   # entries per merge call -- well under Lua 5.1's per-function constant ceiling

NOTE = ("Hash-verified pandemic_hash_m2 -> name lookup for Mercenaries 2. Inverts the ~23k asset / "
        "world-placement names the retail game ships. Built from the Mercs2 workshop's names.bin (the same "
        "source that fills its production_names.json), every entry witnessed against the retail WADs -- no "
        "brute-force guesses. Consumed by Ess.Names (src/07_names.lua) via build/names.py. Regenerate with "
        "that upstream tool; do NOT hand-edit.")


def canon(key):
    """Any spelling of a hash -> "0xAABBCCDD" (0x + upper-case hex, zero-padded to 8)."""
    h = key[2:] if key[:2].lower() == "0x" else key
    h = h.upper().rjust(8, "0")
    if not re.match(r"^[0-9A-F]{8}$", h):
        raise ValueError("not a 32-bit hex hash: %r" % key)
    return "0x" + h


def load_map(path):
    doc = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    raw = doc.get("pandemic_hash_m2", doc)   # accept either the wrapped export or a bare map
    out = {}
    for k, v in raw.items():
        out[canon(k)] = v
    return out


def do_import(src):
    """Rewrite data/names.json from an upstream export, canonically and sorted (a stable, reviewable diff)."""
    m = load_map(src)
    doc = {"format": 1, "note": NOTE, "count": len(m),
           "pandemic_hash_m2": {k: m[k] for k in sorted(m)}}
    DATA.write_text(json.dumps(doc, ensure_ascii=False, indent=0), encoding="utf-8")
    print("[names] imported %d entries -> %s" % (len(m), DATA))


def lua_quote(s):
    """Minimal Lua long-bracket-free string literal. Names are ASCII identifiers, but stay defensive about a
    stray backslash or quote so a bad entry can never produce a syntactically broken table."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def do_build():
    if not DATA.exists():
        print("[names] %s missing -- run `python build/names.py --import <export.json>` first" % DATA)
        return 1
    m = load_map(DATA)
    keys = sorted(m)
    DIST.mkdir(exist_ok=True)
    lines = [
        "-- GENERATED by build/names.py from data/names.json -- do NOT edit.",
        "-- The Ess.Names lookup table (%d entries). Opt-in: deploy as scripts/OnLoad/2_EssNames.lua and add" % len(keys),
        "--   [OnLoad]",
        "--   2_EssNames.lua=4",
        "-- to lua_loader.ini. src/07_names.lua adopts the global __EssNamesDB lazily, so load order is free.",
        "local DB = {}",
        "local function a(t) for k, v in pairs(t) do DB[k] = v end end",
    ]
    for i in range(0, len(keys), BATCH):
        parts = ["[%s]=%s" % (lua_quote(k), lua_quote(m[k])) for k in keys[i:i + BATCH]]
        lines.append("a{" + ",".join(parts) + "}")
    lines.append("_G.__EssNamesDB = DB")
    lines.append("if Loader and Loader.Printf then Loader.Printf(\"[EssNames] %d names ready\") end" % len(keys))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("[names] wrote %s (%d entries, %d bytes)" % (OUT, len(keys), OUT.stat().st_size))

    # If the engine's compiler is on PATH, prove the generated table actually compiles under real 5.1 -- the
    # same gate CI runs on dist/Ess.lua. Skipped (not failed) when luac5.1 isn't installed, like the rest of
    # the offline tooling.
    luac = _find_luac()
    if luac:
        r = subprocess.run([luac, "-p", str(OUT)], capture_output=True, text=True)
        if r.returncode != 0:
            print("[names] FATAL: generated table failed luac5.1 -p:\n" + r.stderr)
            return 1
        print("[names] luac5.1 -p OK")
    else:
        print("[names] (luac5.1 not found -- skipping the syntax gate; CI still runs it)")
    return 0


def _find_luac():
    import shutil
    for name in ("luac5.1", "luac"):
        p = shutil.which(name)
        if p:
            return p
    return None


def main(argv):
    if len(argv) >= 2 and argv[1] == "--import":
        if len(argv) < 3:
            print("usage: python build/names.py --import <upstream production_names.json>")
            return 2
        do_import(argv[2])
        return 0
    return do_build()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
